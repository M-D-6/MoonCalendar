  static DateTime _event(int year, double targetDeg, int month, int day) {
    final jdTT = _findEvent(year, targetDeg, month, day);
    final t = (jdTT - _j2000) / 36525.0;
    final correction = _correctionC0 + t * (_correctionC1 + t * _correctionC2);
    final taiUtc = _taiMinusUtc(year, month);
    final jdPosix = jdTT - (correction + 32.184 + taiUtc) / 86400.0;
    final epochMillis = ((jdPosix - _unixEpochJd) * 86400000.0).round();
    return DateTime.fromMillisecondsSinceEpoch(epochMillis, isUtc: true);
  }

  static double _sumSeries(List<double> values, double t) {
    var sum = 0.0;
    for (var i = 0; i + 3 < values.length; i += 4) {
      sum += values[i] * math.pow(t, values[i + 3]).toDouble() *
          math.cos(values[i + 1] + values[i + 2] * t);
    }
    return sum;
  }

  static double _earthLValue(double t) => _sumSeries(_earthL, t);
  static double _earthRValue(double t) => _sumSeries(_earthR, t);

  static double _nutationLongitude(double jdTT) {
    final t = (jdTT - _j2000) / 36525.0;
    var sum = 0.0;
    for (var i = 0; i + 4 < _nutTerms.length; i += 5) {
      final angle = _nutTerms[i] + _nutTerms[i + 1] * t;
      final s = math.sin(angle);
      sum += _nutTerms[i + 2] * s + _nutTerms[i + 3] * s * t +
          _nutTerms[i + 4] * math.cos(angle);
    }
    return (sum - 0.000135e7) * _asec2rad / 1e7;
  }

  static double _apparentLongitude(double jdTT) {
    final t = (jdTT - _j2000) / 365250.0;
    final l = _earthLValue(t);
    final r = _earthRValue(t);
    var lon = (l + math.pi) * 180.0 / math.pi;
    lon -= _aberration / r / 3600.0;
    lon += _nutationLongitude(jdTT) * 180.0 / math.pi;
    lon %= 360.0;
    if (lon < 0) lon += 360.0;
    return lon;
  }

  static int _taiMinusUtc(int year, int month) {
    for (final item in _leapSeconds) {
      if (year > item.year || (year == item.year && month >= item.month)) return item.offset;
    }
    return 10;
  }

  static double _findEvent(int year, double targetDeg, int month, int day) {
    var t = _gregorianToJd(year, month, day);
    for (var i = 0; i < 10; i++) {
      final longitude = _apparentLongitude(t);
      var diff = (longitude - targetDeg + 180.0) % 360.0;
      if (diff < 0) diff += 360.0;
      diff -= 180.0;
      t -= diff / _meanMotion;
    }
    return t;
  }

  static double _gregorianToJd(int year, int month, int day) {
    final a = ((14 - month) / 12).floor();
    final y = year + 4800 - a;
    final m = month + 12 * a - 3;
    final jdn = day + ((153 * m + 2) / 5).floor() + 365 * y + (y / 4).floor() -
        (y / 100).floor() + (y / 400).floor() - 32045;
    return jdn.toDouble();
  }
