final List<int> _iranianMonthStarts = _buildIranianMonthStarts();

List<int> _buildIranianMonthStarts() {
  final List<int> result = <int>[];
  int jd = 0;
  for (final int len in _iranianIslamicMonths) {
    result.add(jd);
    jd += len;
  }
  return result;
}

int islamicMonthLength(int year, int month) {
  if (month < 1 || month > 12) throw ArgumentError.value(month);
  final int index = year - _iranianIslamicStartYear;
  final int flat = index * 12 + month - 1;
  if (index >= 0 && flat >= 0 && flat < _iranianIslamicMonths.length) {
    return _iranianIslamicMonths[flat];
  }
  if (month == 12) {
    final leap = ((11 * year + 14) % 30) < 11;
    return leap ? 30 : 29;
  }
  return month.isOdd ? 30 : 29;
}

int islamicToJdn(int year, int month, int day) {
  if (month < 1 || month > 12 || day < 1 || day > islamicMonthLength(year, month)) {
    throw ArgumentError('Invalid Islamic date');
  }
  final int index = year - _iranianIslamicStartYear;
  if (index >= 0 && index * 12 + month - 1 < _iranianMonthStarts.length) {
    final int start = _iranianMonthStarts[index * 12 + month - 1];
    return _iranianIslamicStartJdn + start + day - 1;
  }
  return day + ((29.5 * (month - 1)).ceil()) +
      (year - 1) * 354 + ((3 + 11 * year) ~/ 30) + 1948439 - 1;
}

DateParts islamicFromJdn(int jdn) {
  final int days = jdn - _iranianIslamicStartJdn;
  if (days >= 0 && days < (_iranianMonthStarts.last + _iranianIslamicMonths.last)) {
    int lo = 0, hi = _iranianMonthStarts.length - 1;
    while (lo < hi) {
      final int mid = (lo + hi + 1) ~/ 2;
      if (_iranianMonthStarts[mid] <= days) {
        lo = mid;
      } else {
        hi = mid - 1;
      }
    }
    final int idx = lo;
    return DateParts(_iranianIslamicStartYear + idx ~/ 12, idx % 12 + 1, days - _iranianMonthStarts[idx] + 1);
  }
  final double h = (30 * (jdn - 1948439) + 10646) / 10631;
  final int year = h.floor();
  final int dayOfYear = jdn - islamicToJdn(year, 1, 1) + 1;
  final int month = math.min(12, ((dayOfYear - 1) / 29.5).floor() + 1);
  final int day = jdn - islamicToJdn(year, month, 1) + 1;
  return DateParts(year, month, day);
}

int dayOfWeekFromJdn(int jdn) => (jdn + 2) % 7; // 0=Saturday ... 6=Friday

String toPersianDigits(Object value) {
  const String latin = '0123456789';
  const String persian = '۰۱۲۳۴۵۶۷۸۹';
  final String s = value.toString();
  return s.split('').map((String c) {
    final int i = latin.indexOf(c);
    return i >= 0 ? persian[i] : c;
  }).join();
}

