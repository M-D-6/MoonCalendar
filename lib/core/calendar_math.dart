import 'old_persian_data.dart';

class DateParts {
  final int year;
  final int month;
  final int day;
  const DateParts(this.year, this.month, this.day);
  @override
  String toString() => '$year-${month.toString().padLeft(2, '0')}-${day.toString().padLeft(2, '0')}';
}

const List<int> persianLeapYears = <int>[1304, 1309, 1313, 1317, 1321, 1325, 1329, 1333, 1337, 1342, 1346, 1350, 1354, 1358, 1362, 1366, 1370, 1375, 1379, 1383, 1387, 1391, 1395, 1399, 1403, 1408, 1412, 1416, 1420, 1424, 1428, 1432, 1436, 1441, 1445, 1449, 1453, 1457, 1461, 1465, 1469, 1474, 1478, 1482, 1486, 1490, 1494, 1498];

const int _oldPersianStartYear = 1220;
const int _oldPersianEndYear = 1303;
const int _persianStartYear = 1304;
const int _persianStartJdn = 2424231;

bool _isOldEraYear(int year) => year >= _oldPersianStartYear && year <= _oldPersianEndYear;

int _oldEraYearOffset(int year) => (year - _oldPersianStartYear) * 12;

int _oldEraMonthLength(int year, int month) =>
    oldEraPersianMonthLengths[_oldEraYearOffset(year) + month - 1];

int _oldEraMonthStartDays(int year, int month) {
  final int offset = _oldEraYearOffset(year);
  int days = 0;
  for (int m = 1; m < month; m++) {
    days += oldEraPersianMonthLengths[offset + m - 1];
  }
  return days;
}

int _oldEraYearStartJdn(int year) {
  int jdn = 2393551;
  for (int y = _oldPersianStartYear; y < year; y++) {
    for (int m = 1; m <= 12; m++) {
      jdn += _oldEraMonthLength(y, m);
    }
  }
  return jdn;
}

int _persianDaysBeforeYear(int year) {
  if (_isOldEraYear(year)) return _oldEraYearStartJdn(year) - _persianStartJdn;
  if (year < _persianStartYear) {
    int y = _persianStartYear;
    int d = 0;
    while (y > year) {
      y--;
      d += persianYearLength(y);
    }
    return -d;
  }
  int days = 0;
  for (int y = _persianStartYear; y < year; y++) {
    days += persianYearLength(y);
  }
  return days;
}

bool persianIsLeap(int year) {
  if (year >= 1304 && year <= 1498) return persianLeapYears.contains(year);
  if (_isOldEraYear(year)) {
    return _oldEraMonthLength(year, 12) == 30;
  }
  // Deterministic fallback for dates outside the embedded official lookup table.
  const List<int> cycle = <int>[1, 5, 9, 13, 17, 22, 26, 30];
  final int mod = ((year - 1) % 33 + 33) % 33;
  return cycle.contains(mod);
}

int persianYearLength(int year) {
  if (_isOldEraYear(year)) {
    final int offset = _oldEraYearOffset(year);
    return oldEraPersianMonthLengths.sublist(offset, offset + 12).fold(0, (a, b) => a + b);
  }
  return persianIsLeap(year) ? 366 : 365;
}

int persianMonthLength(int year, int month) {
  if (month < 1 || month > 12) throw ArgumentError.value(month);
  if (_isOldEraYear(year)) return _oldEraMonthLength(year, month);
  if (month <= 6) return 31;
  if (month <= 11) return 30;
  return persianIsLeap(year) ? 30 : 29;
}

int persianToJdn(int year, int month, int day) {
  if (month < 1 || month > 12 || day < 1 || day > persianMonthLength(year, month)) {
    throw ArgumentError('Invalid Persian date');
  }
  if (_isOldEraYear(year)) {
    return _oldEraYearStartJdn(year) + _oldEraMonthStartDays(year, month) + day - 1;
  }
  return _persianStartJdn + _persianDaysBeforeYear(year) + _persianMonthDaysBefore(month) + day - 1;
}

// Computed once (top-level finals are lazy) instead of on every call.
final int _oldEraFirstJdn = _oldEraYearStartJdn(_oldPersianStartYear);
final int _oldEraLastJdn = _oldEraYearStartJdn(_oldPersianEndYear) + persianYearLength(_oldPersianEndYear) - 1;

DateParts persianFromJdn(int jdn) {
  final int oldStart = _oldEraFirstJdn;
  final int oldEnd = _oldEraLastJdn;
  if (jdn >= oldStart && jdn <= oldEnd) {
    int lo = _oldPersianStartYear, hi = _oldPersianEndYear;
    while (lo <= hi) {
      final int mid = (lo + hi) ~/ 2;
      final int start = _oldEraYearStartJdn(mid);
      final int next = start + persianYearLength(mid);
      if (jdn >= start && jdn < next) {
        int remaining = jdn - start;
        int m = 1;
        while (remaining >= persianMonthLength(mid, m)) {
          remaining -= persianMonthLength(mid, m);
          m++;
        }
        return DateParts(mid, m, remaining + 1);
      }
      if (jdn < start) {
        hi = mid - 1;
      } else {
        lo = mid + 1;
      }
    }
  }
  if (jdn >= _persianStartJdn && jdn <= persianToJdn(1498, 12, 30)) {
    int lo = _persianStartYear, hi = 1498;
    while (lo <= hi) {
      final int mid = (lo + hi) ~/ 2;
      final int start = persianToJdn(mid, 1, 1);
      final int next = mid == 1498 ? start + (persianIsLeap(mid) ? 366 : 365) : persianToJdn(mid + 1, 1, 1);
      if (jdn >= start && jdn < next) {
        final int doy = jdn - start + 1;
        return _persianFromDayOfYear(mid, doy);
      }
      if (jdn < start) {
        hi = mid - 1;
      } else {
        lo = mid + 1;
      }
    }
  }
  // Deterministic compatibility fallback for dates outside the source lookup table.
  const int anchorYear = 1404;
  final int anchor = persianToJdn(anchorYear, 1, 1);
  int year = anchorYear;
  int start = anchor;
  if (jdn >= anchor) {
    while (jdn >= start + (persianIsLeap(year) ? 366 : 365)) {
      start += persianIsLeap(year) ? 366 : 365;
      year++;
    }
  } else {
    while (jdn < start) {
      year--;
      start -= persianIsLeap(year) ? 366 : 365;
    }
  }
  return _persianFromDayOfYear(year, jdn - start + 1);
}

DateParts _persianFromDayOfYear(int year, int doy) {
  final int month = doy <= 186 ? ((doy - 1) ~/ 31) + 1 : ((doy - 187) ~/ 30) + 7;
  final int before = _persianMonthDaysBefore(month);
  return DateParts(year, month, doy - before);
}

int _persianMonthDaysBefore(int month) => month <= 7 ? (month - 1) * 31 : 186 + (month - 7) * 30;

int gregorianToJdn(int year, int month, int day) {
  final int a = (14 - month) ~/ 12;
  final int y = year + 4800 - a;
  final int m = month + 12 * a - 3;
  return day + ((153 * m + 2) ~/ 5) + 365 * y + y ~/ 4 - y ~/ 100 + y ~/ 400 - 32045;
}

DateParts gregorianFromJdn(int jdn) {
  final int a = jdn + 32044;
  final int b = (4 * a + 3) ~/ 146097;
  final int c = a - (146097 * b) ~/ 4;
  final int d = (4 * c + 3) ~/ 1461;
  final int e = c - (1461 * d) ~/ 4;
  final int m = (5 * e + 2) ~/ 153;
  final int day = e - (153 * m + 2) ~/ 5 + 1;
  final int month = m + 3 - 12 * (m ~/ 10);
  final int year = 100 * b + d - 4800 + m ~/ 10;
  return DateParts(year, month, day);
}

