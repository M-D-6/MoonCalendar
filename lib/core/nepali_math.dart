final List<int> _starts = _makeStarts();

List<int> _makeStarts() {
  final List<int> s = <int>[]; int d = 0;
  for (final int v in nepaliMonthLengths) { s.add(d); d += v; }
  return s;
}

int _yearIndex(int year) => year - nepaliStartYear;

int nepaliMonthLength(int year, int month) {
  if (month < 1 || month > 12) throw ArgumentError.value(month);
  const cycleYears = 225;
  final int cycle = ((year - nepaliStartYear) / cycleYears).floor();
  final int cycleYear = year - cycle * cycleYears;
  final int idx = _yearIndex(cycleYear);
  return nepaliMonthLengths[idx * 12 + month - 1];
}

int nepaliToJdn(int year, int month, int day) {
  if (month < 1 || month > 12 || day < 1 || day > nepaliMonthLength(year, month)) {
    throw ArgumentError('Invalid Nepali date');
  }
  const cycleYears = 225;
  final int cycle = ((year - nepaliStartYear) / cycleYears).floor();
  final int cycleYear = year - cycle * cycleYears;
  final int idx = _yearIndex(cycleYear);
  return nepaliStartJdn + cycle * (_starts.last + nepaliMonthLengths.last) +
      _starts[idx * 12 + month - 1] + day - 1;
}

DateParts nepaliFromJdn(int jdn) {
  final int totalDays = _starts.last + nepaliMonthLengths.last;
  final int eras = ((jdn - nepaliStartJdn) / totalDays).floor();
  int local = jdn - nepaliStartJdn - eras * totalDays;
  if (local < 0) local += totalDays;
  int idx = (local / 31.26).floor().clamp(0, _starts.length - 1);
  while (idx + 1 < _starts.length && _starts[idx + 1] <= local) {
    idx++;
  }
  final int year = nepaliStartYear + eras * (nepaliMonthLengths.length ~/ 12) + idx ~/ 12;
  return DateParts(year, idx % 12 + 1, local - _starts[idx] + 1);
}
